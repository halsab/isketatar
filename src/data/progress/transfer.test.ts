import 'fake-indexeddb/auto';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { catalog, correctAnswer, now } from '../../../tests/learning-fixture';
import { ProgressRepository, expectedFrom } from './repository';
import { MAX_EXPORT_BYTES, decodeImport, encodeExport, replacementToken } from './transfer';
import { recordBytes, SOFT_BYTES } from './model';
import type { ProgressExport } from './model';

const opened: ProgressRepository[] = [];
async function open() {
  const repository = await ProgressRepository.open({ catalog, releaseId: 'test-release', name: crypto.randomUUID(), clock: () => now });
  opened.push(repository); return repository;
}
afterEach(() => { for (const repository of opened.splice(0)) repository.close(); });
const blob = (data: unknown) => new Blob([JSON.stringify(data)], { type: 'application/json' });
async function answered() {
  const repository = await open();
  const started = await repository.dispatch({ type: 'start', kind: 'lesson_cycle', lesson_id: 'V04' }, expectedFrom(await repository.snapshot()));
  await repository.dispatch({ type: 'show', presentation_id: started.presentation_id! }, expectedFrom(await repository.snapshot()));
  await repository.dispatch({ type: 'submit', presentation_id: started.presentation_id!, answer: correctAnswer('Q-V04-01') }, expectedFrom(await repository.snapshot()));
  return repository;
}
describe('bounded and atomic progress transfer', () => {
  it('exports one snapshot and restores an active session as paused with a new generation', async () => {
    const source = await answered();
    const file = await source.exportProgress();
    const target = await open();
    const before = await target.snapshot();
    const preview = await target.previewImport(file);
    expect(preview.recognized_attempts).toBe(1);
    await target.commitImport(preview.id, true);
    const restored = await target.snapshot();
    expect(restored.attempts).toEqual((await source.snapshot()).attempts);
    expect(restored.sessions[0]!.status).toBe('paused');
    expect(restored.sessions[0]!.data_generation).toBe(restored.control.data_generation);
    expect(restored.control.data_generation).not.toBe(before.control.data_generation);
    expect(restored.control.active_session_id).toBeNull();
    await expect(target.dispatch({ type: 'settings', patch: { theme: 'dark' } }, expectedFrom(before))).rejects.toThrow('write_conflict');
    await expect(target.commitImport(preview.id, true)).rejects.toThrow('invalid_preview');
  });
  it('rejects stale preview and leaves the entire existing dataset unchanged', async () => {
    const repository = await answered();
    const preview = await repository.previewImport(await repository.exportProgress());
    await repository.dispatch({ type: 'settings', patch: { theme: 'dark' } }, expectedFrom(await repository.snapshot()));
    const before = await repository.snapshot();
    await expect(repository.commitImport(preview.id, true)).rejects.toThrow('write_conflict');
    expect(await repository.snapshot()).toEqual(before);
  });
  it('rejects invalid UTF-8, size, depth, dangerous keys and unknown schema before writing', async () => {
    const repository = await open();
    const original = await repository.exportProgress();
    const value = JSON.parse(await original.text()) as ProgressExport;
    await expect(decodeImport(new Blob([new Uint8Array([0xc3, 0x28])]))).rejects.toThrow('invalid_import');
    await expect(decodeImport(new Blob([new Uint8Array(MAX_EXPORT_BYTES + 1)]))).rejects.toThrow('import_too_large');
    await expect(decodeImport(blob({ ...value, schema_version: 2 }))).rejects.toThrow('unsupported_import');
    await expect(decodeImport(new Blob(['{"__proto__": {}}']))).rejects.toThrow('invalid_import');
    await expect(decodeImport(new Blob(['['.repeat(34) + '0' + ']'.repeat(34)]))).rejects.toThrow('invalid_import');
    await expect(repository.previewImport(blob({ ...value, data: { ...value.data, extra: true } }))).rejects.toThrow('invalid_import');
  });
  it('regrades known answers and refuses broken internal references', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    value.data.attempts[0]!.grade = 'incorrect';
    value.data.attempts[0]!.independent_correct = false;
    const target = await open();
    const preview = await target.previewImport(blob(value));
    await target.commitImport(preview.id, true);
    expect((await target.snapshot()).attempts[0]).toMatchObject({ grade: 'correct', independent_correct: true });
    value.data.presentations = [];
    await expect(target.previewImport(blob(value))).rejects.toThrow('invalid_import');
  });
  it('preserves an unknown grading revision and its dependencies in legacy without grading by a new key', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    const question = value.data.attempts[0]!.question_id;
    value.data.attempts[0]!.grading_revision = 'f'.repeat(64);
    value.data.presentations.find(item => item.question_id === question)!.grading_revision = 'f'.repeat(64);
    value.data.sessions[0]!.question_plan.find(item => item.question_id === question)!.grading_revision = 'f'.repeat(64);
    const target = await open();
    const preview = await target.previewImport(blob(value));
    expect(preview.legacy_records).toBeGreaterThan(0);
    await target.commitImport(preview.id, true);
    const restored = await target.snapshot();
    expect(restored.attempts).toEqual([]);
    expect(restored.legacy.some(item => item.origin_kind === 'attempt' && 'grade' in item.record && item.record.grade === 'correct')).toBe(true);
    const roundtrip = await target.previewImport(await target.exportProgress());
    await target.commitImport(roundtrip.id, true);
    expect((await target.snapshot()).legacy).toEqual(restored.legacy);
  });
  it('resets atomically only with explicit confirmation and rejects a late callback', async () => {
    const repository = await answered();
    const before = await repository.snapshot();
    await expect(repository.reset(replacementToken(before), false)).rejects.toThrow('confirmation_required');
    expect(await repository.snapshot()).toEqual(before);
    await repository.reset(replacementToken(before), true);
    const after = await repository.snapshot();
    expect(after.attempts).toEqual([]);
    expect(after.sessions).toEqual([]);
    expect(after.settings.revision).toBe(0);
    await expect(repository.dispatch({ type: 'draft', presentation_id: before.presentations[0]!.presentation_id, answer: null }, expectedFrom(before))).rejects.toThrow('write_conflict');
    expect(encodeExport(after, '1.0.0', catalog.core.content_version, now).size).toBeLessThan(MAX_EXPORT_BYTES);
  });
  it('rolls back an import quota failure after clearing stores and permits retry of the same preview', async () => {
    const source = await answered();
    const target = await open();
    await target.dispatch({ type: 'settings', patch: { theme: 'dark' } }, expectedFrom(await target.snapshot()));
    const preview = await target.previewImport(await source.exportProgress());
    const before = await target.snapshot();
    const run = target.backend.run.bind(target.backend);
    vi.spyOn(target.backend, 'run').mockImplementationOnce((mode, body) => run(mode, async tx => {
      const put = tx.put.bind(tx);
      tx.put = async (store, value) => { await put(store, value); if (store === 'presentations') throw new DOMException('test quota', 'QuotaExceededError'); };
      return body(tx);
    }));
    await expect(target.commitImport(preview.id, true)).rejects.toThrow('storage_full');
    expect(await target.snapshot()).toEqual(before);
    await target.commitImport(preview.id, true);
    const after = await target.snapshot();
    expect(after.attempts).toHaveLength(1);
    const { control, ...data } = after;
    const bytes = recordBytes(data.settings) + Object.entries(data).filter(([key]) => key !== 'settings').reduce((total, [, values]) => total + (values as unknown[]).reduce<number>((size, value) => size + recordBytes(value), 0), 0);
    expect(control.estimated_record_bytes).toBe(bytes);
  });
  it('preserves the first independent reading result when a later retry opened line help', async () => {
    const source = await open();
    const started = await source.dispatch({ type: 'start', kind: 'reading_practice', reading_id: 'READ-01' }, expectedFrom(await source.snapshot()));
    const initial = (await source.snapshot()).presentations.find(item => item.presentation_id === started.presentation_id)!;
    const question = catalog.question(initial.question_id);
    await source.dispatch({ type: 'show', presentation_id: initial.presentation_id }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'submit', presentation_id: initial.presentation_id, answer: correctAnswer(question.id) }, expectedFrom(await source.snapshot()));
    const first = (await source.snapshot()).attempts[0]!;
    const retry = await source.dispatch({ type: 'retry', presentation_id: initial.presentation_id }, expectedFrom(await source.snapshot()));
    const line = catalog.readings.get('READ-01')!.lines.find(item => question.line_ids.includes(item.id))!;
    await source.dispatch({ type: 'observe', target: { kind: 'reading_line', id: line.id, line_id: line.id, reading_id: 'READ-01', level: 'reading' }, confirm_assessment_help: false }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'show', presentation_id: retry.presentation_id! }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'submit', presentation_id: retry.presentation_id!, answer: correctAnswer(question.id) }, expectedFrom(await source.snapshot()));
    const target = await open();
    const preview = await target.previewImport(await source.exportProgress());
    await target.commitImport(preview.id, true);
    const attempts = (await target.snapshot()).attempts;
    expect(attempts.find(item => item.presentation_id === first.presentation_id)).toEqual(first);
    expect(first.independent_correct).toBe(true);
    expect(attempts.find(item => item.presentation_id === retry.presentation_id)!.assistance_before_submit.reference_opened_at).not.toBeNull();
  });
  it('accepts exactly 20 MiB and treats dangerous-looking answer text as ordinary text', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    const serialized = JSON.stringify(value);
    const padded = new Blob([serialized, ' '.repeat(MAX_EXPORT_BYTES - new TextEncoder().encode(serialized).byteLength)]);
    expect(padded.size).toBe(MAX_EXPORT_BYTES);
    expect((await decodeImport(padded)).format).toBe('iske-imla-progress');
    value.data.presentations[0]!.draft_answer = { kind: 'text', text: '__proto__ constructor prototype' };
    expect((await decodeImport(blob(value))).data.presentations[0]!.draft_answer).toEqual(value.data.presentations[0]!.draft_answer);
  });
  it('keeps history readable and exportable at the soft limit while refusing new history', async () => {
    const source = await answered();
    const before = await source.snapshot();
    await source.backend.run('readwrite', tx => tx.put('meta', { ...before.control, estimated_record_bytes: SOFT_BYTES }));
    await expect(source.dispatch({ type: 'observe', target: { kind: 'lesson', id: 'V04' }, confirm_assessment_help: false }, expectedFrom(before))).rejects.toThrow('history_full');
    await source.dispatch({ type: 'settings', patch: { theme: 'dark' } }, expectedFrom(before));
    expect((await source.exportProgress()).size).toBeGreaterThan(0);
    expect((await source.snapshot()).attempts).toEqual(before.attempts);
  });
  it('keeps unavailable pinned drafts and unknown policies as legacy and refuses forged local references', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    const target = await open();
    value.data.sessions[0]!.release_id = 'unavailable-release';
    value.data.attempts[0]!.release_id = 'unavailable-release';
    let preview = await target.previewImport(blob(value));
    await target.commitImport(preview.id, true);
    expect((await target.snapshot()).legacy[0]!.reason).toBe('incompatible_draft');
    Reflect.set(value.data.sessions[0]!.policy_versions, 'grading', 'grading/999');
    Reflect.set(value.data.attempts[0]!.policy_versions, 'grading', 'grading/999');
    preview = await target.previewImport(blob(value));
    await target.commitImport(preview.id, true);
    expect((await target.snapshot()).legacy.every(item => item.reason === 'unknown_policy_version')).toBe(true);
    value.data.attempts[0]!.session_id = crypto.randomUUID();
    await expect(target.previewImport(blob(value))).rejects.toThrow('invalid_import');
  });
  it('blocks reset and import during update commit and respects cancellation', async () => {
    const source = await answered();
    const file = await source.exportProgress();
    const cancelled = await source.previewImport(file);
    source.cancelImport();
    await expect(source.commitImport(cancelled.id, true)).rejects.toThrow('invalid_preview');
    const before = await source.snapshot();
    await source.backend.run('readwrite', tx => tx.put('meta', { ...before.control, update_gate: { update_id: crypto.randomUUID(), target_release_id: 'next', phase: 'commit', coordinator_id: source.tabId, requested_at: now } }));
    const preview = await source.previewImport(file);
    const gated = await source.snapshot();
    await expect(source.commitImport(preview.id, true)).rejects.toThrow('update_in_progress');
    await expect(source.reset(replacementToken(gated), true)).rejects.toThrow('update_in_progress');
    expect(await source.snapshot()).toEqual(gated);
  });
  it('accepts a technically imported empty set as incorrect without allowing it in ordinary UI submit', async () => {
    const source = await open();
    await source.dispatch({ type: 'review_add', question_id: 'Q-B01-06', origin: { kind: 'manual', id: 'Q-B01-06' } }, expectedFrom(await source.snapshot()));
    const start = await source.dispatch({ type: 'start', kind: 'review', early_question_ids: ['Q-B01-06'] }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'show', presentation_id: start.presentation_id! }, expectedFrom(await source.snapshot()));
    await expect(source.dispatch({ type: 'submit', presentation_id: start.presentation_id!, answer: { kind: 'set', option_ids: [] } }, expectedFrom(await source.snapshot()))).rejects.toThrow('invalid_answer');
    await source.dispatch({ type: 'submit', presentation_id: start.presentation_id!, answer: { kind: 'unknown' } }, expectedFrom(await source.snapshot()));
    const value = await decodeImport(await source.exportProgress());
    value.data.attempts[0]!.answer_raw = { kind: 'set', option_ids: [] };
    value.data.presentations[0]!.draft_answer = { kind: 'set', option_ids: [] };
    value.data.review_cards[0]!.unknown_count = 0;
    value.data.review_cards[0]!.incorrect_count = 1;
    const target = await open();
    const preview = await target.previewImport(blob(value));
    await target.commitImport(preview.id, true);
    expect((await target.snapshot()).attempts[0]).toMatchObject({ grade: 'incorrect', independent_correct: false, answer_normalized: [] });
  });
  it('rejects a current session whose presentations were moved into legacy', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    for (const record of value.data.presentations) value.data.legacy.push({ legacy_id: `presentation:${record.presentation_id}`, origin_kind: 'presentation', original_id: record.presentation_id, source_content_version: value.content_version, reason: 'unknown_grading_revision', record, imported_at: now });
    value.data.presentations = [];
    const target = await open();
    await expect(target.previewImport(blob(value))).rejects.toThrow('invalid_import');
    expect((await target.snapshot()).sessions).toEqual([]);
  });
  it('rejects an active retry that exists only in legacy', async () => {
    const source = await answered();
    const first = (await source.snapshot()).attempts[0]!;
    const retry = await source.dispatch({ type: 'retry', presentation_id: first.presentation_id }, expectedFrom(await source.snapshot()));
    const value = await decodeImport(await source.exportProgress());
    const record = value.data.presentations.find(item => item.presentation_id === retry.presentation_id)!;
    value.data.legacy.push({ legacy_id: `presentation:${record.presentation_id}`, origin_kind: 'presentation', original_id: record.presentation_id, source_content_version: value.content_version, reason: 'unknown_grading_revision', record, imported_at: now });
    value.data.presentations = value.data.presentations.filter(item => item !== record);
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
  });
  it('checks UTF-16 length and exact-revision answer types before classifying unknown policies', async () => {
    const source = await answered();
    const value = await decodeImport(await source.exportProgress());
    Reflect.set(value.data.sessions[0]!.policy_versions, 'grading', 'grading/unknown');
    Reflect.set(value.data.attempts[0]!.policy_versions, 'grading', 'grading/unknown');
    const presentation = value.data.presentations.find(item => item.presentation_id === value.data.attempts[0]!.presentation_id)!;
    value.data.attempts[0]!.answer_raw = presentation.draft_answer = { kind: 'text', text: '😀'.repeat(4096) };
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
    value.data.attempts[0]!.answer_raw = presentation.draft_answer = { kind: 'option', option_id: 'nonexistent-option' };
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
  });
  it('does not discard submitted grades because an unrelated search policy changed', async () => {
    const source = await open();
    const session = await source.dispatch({ type: 'start', kind: 'final' }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'finish_assessment', session_id: session.session_id!, confirm_incomplete: true, defer_imla: false }, expectedFrom(await source.snapshot()));
    const value = await decodeImport(await source.exportProgress());
    Reflect.set(value.data.sessions[0]!.policy_versions, 'search', 'dictionary-search/older');
    for (const attempt of value.data.attempts) Reflect.set(attempt.policy_versions, 'search', 'dictionary-search/older');
    const preview = await source.previewImport(blob(value));
    expect(preview.recognized_attempts).toBe(20);
    expect(preview.legacy_records).toBe(0);
  });
  it('rejects review counters unsupported by the first submissions in the file', async () => {
    const source = await answered();
    const before = await source.snapshot();
    const retry = await source.dispatch({ type: 'retry', presentation_id: before.attempts[0]!.presentation_id }, expectedFrom(before));
    await source.dispatch({ type: 'review_add', question_id: 'Q-V04-01', origin: { kind: 'manual', id: 'Q-V04-01' } }, expectedFrom(await source.snapshot()));
    const value = await decodeImport(await source.exportProgress());
    value.data.review_cards[0]!.attempt_count = 90000;
    value.data.review_cards[0]!.unknown_count = 90000;
    value.data.review_cards[0]!.last_scheduled_presentation_id = before.attempts[0]!.presentation_id;
    value.data.review_cards[0]!.last_outcome = 'unknown';
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
    expect((await source.snapshot()).sessions[0]!.active_presentation_id).toBe(retry.presentation_id);
  });
  it('stores and roundtrips the longest invalid segment answer including all empty parts', async () => {
    const source = await open();
    await source.dispatch({ type: 'review_add', question_id: 'Q-A06-09', origin: { kind: 'manual', id: 'Q-A06-09' } }, expectedFrom(await source.snapshot()));
    const started = await source.dispatch({ type: 'start', kind: 'review', early_question_ids: ['Q-A06-09'] }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'show', presentation_id: started.presentation_id! }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'submit', presentation_id: started.presentation_id!, answer: { kind: 'segments', text: '+'.repeat(4096) } }, expectedFrom(await source.snapshot()));
    const original = (await source.snapshot()).attempts[0]!;
    expect(original.grade).toBe('incorrect');
    expect(original.answer_normalized).toHaveLength(4097);
    const preview = await source.previewImport(await source.exportProgress());
    await source.commitImport(preview.id, true);
    expect((await source.snapshot()).attempts[0]).toEqual(original);
  });
  it('rejects zero or missing outcome counters for an existing last scheduled submission', async () => {
    const source = await open();
    const started = await source.dispatch({ type: 'start', kind: 'lesson_cycle', lesson_id: 'V04' }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'show', presentation_id: started.presentation_id! }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'submit', presentation_id: started.presentation_id!, answer: { kind: 'unknown' } }, expectedFrom(await source.snapshot()));
    const value = await decodeImport(await source.exportProgress());
    value.data.review_cards[0]!.attempt_count = 0; value.data.review_cards[0]!.unknown_count = 0;
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
    value.data.review_cards[0]!.attempt_count = 1;
    await expect(source.previewImport(blob(value))).rejects.toThrow('invalid_import');
  });
  it('permits NFC to expand a valid raw answer without treating it as oversized input', async () => {
    const source = await open();
    const started = await source.dispatch({ type: 'start', kind: 'lesson_cycle', lesson_id: 'V04' }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'show', presentation_id: started.presentation_id! }, expectedFrom(await source.snapshot()));
    await source.dispatch({ type: 'submit', presentation_id: started.presentation_id!, answer: { kind: 'text', text: '\u0344'.repeat(4096) } }, expectedFrom(await source.snapshot()));
    const original = (await source.snapshot()).attempts[0]!;
    expect(original.answer_normalized).toHaveLength(8192);
    const preview = await source.previewImport(await source.exportProgress());
    await source.commitImport(preview.id, true);
    expect((await source.snapshot()).attempts[0]).toEqual(original);
  });
});
